import numpy as np
import heapq
import time
from itertools import count

GOAL_STATES = [
    # Chuẩn trái->phải, trên->dưới, blank ở góc dưới-phải
    [1,2,3,4,5,6,7,8,0],
    # Đảo ngược, blank ở góc dưới-phải
    [8,7,6,5,4,3,2,1,0],
    # Chuẩn nhưng blank ở góc trên-phải
    [1,2,0,3,4,5,6,7,8],
    # Đảo ngược nhưng blank ở góc dưới-trái (ví dụ)
    [8,7,6,5,4,3,0,2,1],
]

def is_goal(state: list[int]) -> bool:
    t = tuple(state)
    return any(t == tuple(g) for g in GOAL_STATES)

def misplaced_div2(state: list[int]) -> int:
    # Tính số ô sai vị trí đối với từng goal, lấy min rồi chia 2.
    best_mis = min(
        sum(1 for i in range(9) if state[i] != 0 and state[i] != goal[i])
        for goal in GOAL_STATES
    )
    return best_mis // 2

def manhattan_blank(state: list[int]) -> int:
    i = state.index(0)
    r, c = divmod(i, 3)
    best = 10
    for goal in GOAL_STATES:
        gi = goal.index(0)
        gr, gc = divmod(gi, 3)
        d = abs(r - gr) + abs(c - gc)
        if d < best: best = d
    return best

def heuristic_h2(state: list[int]) -> int:
    return min(misplaced_div2(state), manhattan_blank(state))

def expand(state: list[int]) -> list[list[int]]:
    succ = []

    # 1) Slide blank
    b = state.index(0)
    r, c = divmod(b, 3)
    for dr, dc in [(1,0),(-1,0),(0,1),(0,-1)]:
        nr, nc = r+dr, c+dc
        if 0 <= nr < 3 and 0 <= nc < 3:
            j = nr*3 + nc
            ns = state.copy()
            ns[b], ns[j] = ns[j], ns[b]
            succ.append(ns)

    # 2) Adj9Swap (cặp kề ngang/dọc, tổng = 9, không chứa blank)
    def try_swap(i, j):
        if state[i] != 0 and state[j] != 0 and (state[i] + state[j] == 9):
            ns = state.copy()
            ns[i], ns[j] = ns[j], ns[i]
            succ.append(ns)

    # Ngang
    for rr in range(3):
        i = rr*3+0; j = rr*3+1; k = rr*3+2
        try_swap(i, j)
        try_swap(j, k)
    # Dọc
    for cc in range(3):
        i = 0*3+cc; j = 1*3+cc; k = 2*3+cc
        try_swap(i, j)
        try_swap(j, k)

    # 3) CornerDiagSwap (không swap nếu dính blank)
    for (r1,c1),(r2,c2) in [((0,0),(2,2)), ((0,2),(2,0))]:
        i, j = r1*3+c1, r2*3+c2
        if state[i] != 0 and state[j] != 0:
            ns = state.copy()
            ns[i], ns[j] = ns[j], ns[i]
            succ.append(ns)

    return succ

import heapq

def a_star(start: list[int], h):
    s = tuple(start)
    open_heap = []  # (f, g, state_tuple)
    heapq.heappush(open_heap, (h(start), 0, s))
    g_cost = {s: 0}
    parent = {s: None}

    while open_heap:
        f, g, u = heapq.heappop(open_heap)
        if is_goal(list(u)):
            # reconstruct
            path = []
            cur = u
            while cur is not None:
                path.append(list(cur))
                cur = parent[cur]
            return list(reversed(path))

        for v in map(tuple, expand(list(u))):
            alt = g + 1
            if v not in g_cost or alt < g_cost[v]:
                g_cost[v] = alt
                parent[v] = u
                heapq.heappush(open_heap, (alt + h(list(v)), alt, v))
    return None

