def misplaced_div2(state: List[int]) -> int:
    """
    Heuristic h1: số ô sai vị trí chia 2.
    Dựa trên giả định có thể sửa 2 ô trong 1 bước swap (Adj9 hoặc CornerDiag).
    """
    best = float('inf')
    for goal in goal_states:
        misplaced = sum(1 for i in range(9) if state[i] != 0 and state[i] != goal[i])
        h = misplaced // 2
        if h < best:
            best = h
    return best


def manhattan_blank(state: List[int]) -> int:
    """
    Tính khoảng cách Manhattan của blank (ô 0) tới vị trí blank trong các goal states.
    """
    idx_blank = state.index(0)
    r, c = divmod(idx_blank, 3)
    best = float('inf')
    for goal in goal_states:
        gi = goal.index(0)
        gr, gc = divmod(gi, 3)
        dist = abs(r - gr) + abs(c - gc)
        if dist < best:
            best = dist
    return best


def heuristic_h2(state: List[int]) -> int:
    """
    Heuristic h2 = min(h1, manhattan_blank)
    → chọn ước lượng thấp hơn giữa độ sai vị trí/2 và khoảng cách di chuyển của blank.
    """
    return min(misplaced_div2(state), manhattan_blank(state))

