def a_star(start: List[int], heuristic_func) -> Optional[List[List[int]]]:
    open_set = []
    heapq.heappush(open_set, (heuristic_func(start), 0, start, [start]))  # (f,g,state,path)
    visited = {tuple(start): 0}

    while open_set:
        f, g, current, path = heapq.heappop(open_set)
        if is_goal(current):
            return path

        for nxt in expand(current):
            new_g = g + 1
            key = tuple(nxt)
            if key not in visited or new_g < visited[key]:
                visited[key] = new_g
                new_f = new_g + heuristic_func(nxt)
                heapq.heappush(open_set, (new_f, new_g, nxt, path + [nxt]))
    return None

